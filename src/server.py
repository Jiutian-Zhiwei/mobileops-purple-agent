import argparse
import uvicorn

from a2a.server.apps import A2AStarletteApplication
from a2a.server.request_handlers import DefaultRequestHandler
from a2a.server.tasks import InMemoryTaskStore
from a2a.types import (
    AgentCapabilities,
    AgentCard,
    AgentSkill,
)

from executor import Executor


def main():
    parser = argparse.ArgumentParser(description="Run the mobileops-agent (tau2-bench telecom).")
    parser.add_argument("--host", type=str, default="0.0.0.0", help="Host to bind the server")
    parser.add_argument("--port", type=int, default=9009, help="Port to bind the server")
    parser.add_argument("--card-url", type=str, help="URL to advertise in the agent card")
    args = parser.parse_args()

    skill = AgentSkill(
        id="mobileops_telecom",
        name="mobileops telecom agent",
        description=(
            "Deterministic policy-compliance agent for tau2-bench telecom customer-service tasks: "
            "account management, billing/plan changes, and device/connectivity troubleshooting."
        ),
        tags=["tau2-bench", "telecom", "customer-service", "policy-compliance"],
    )

    agent_card = AgentCard(
        name="mobileops-agent",
        description=(
            "mobileops-agent for tau2-bench telecom: deterministic policy-routing (Runbook rules) "
            "with an LLM fallback for device troubleshooting."
        ),
        url=args.card_url or f"http://{args.host}:{args.port}/",
        version="1.0.0",
        default_input_modes=["text"],
        default_output_modes=["text"],
        capabilities=AgentCapabilities(streaming=True),
        skills=[skill],
    )

    request_handler = DefaultRequestHandler(
        agent_executor=Executor(),
        task_store=InMemoryTaskStore(),
    )
    server = A2AStarletteApplication(
        agent_card=agent_card,
        http_handler=request_handler,
    )
    uvicorn.run(server.build(), host=args.host, port=args.port)


if __name__ == "__main__":
    main()
